"""Engine switching with Quadlet units (ARCHITECTURE.md, Engines).

Each profile is a `kiln-<profile>.container` Quadlet file. The units conflict
with one another so systemd itself never runs two engines, and only the active
profile is wanted by default.target, so the choice survives a reboot. A
switch stops the current engine, waits for the GPU memory to come back, starts
the target and only marks it ready after a real generation succeeds.
"""
from __future__ import annotations

import asyncio
import contextlib
import json
import shutil
import time
from dataclasses import replace
from pathlib import Path
from typing import Awaitable, Callable

import aiohttp

from kiln.config import Config, Profile
from kiln.systemd_quote import literal
from kiln.engines.lock import EvalLock
from kiln.engines.state import FAILED, READY, STARTING, STOPPED, STOPPING, ActiveState, StateFile

GTT_IDLE_BYTES = 4 * 2**30  # below this the previous engine's memory is back
GTT_WAIT_S = 120
STOP_TIMEOUT_S = 120
PROBE_EVERY_S = 5
PROBE_TIMEOUT = aiohttp.ClientTimeout(total=120)
PROBE_CLIENT = "kiln-probe"
# llama.cpp answers 503 while it loads the weights; any other HTTP answer means the server is up and the
# test generation is what is left.
LOADING_STATUS = "HTTP 503"
# Rootless podman makes the user's namespace (and its pause process) at the first call after a boot, with
# newuidmap. newuidmap needs file capabilities, which kiln-dash cannot gain (NoNewPrivileges=yes), so that
# first call fails there. systemd-run starts podman as a unit of the user manager, outside those limits;
# the namespace then stays (the pause process lives in its own scope) and every later call joins it.
USERNS_MARKERS = ("newuidmap", "cannot set up namespace")
USERNS_MAKE = ("systemd-run", "--user", "--wait", "--quiet", "--collect", "podman", "unshare", "true")
# The blocked check runs every 5 s. A failed repair is tried again after USERNS_RETRY_S, and even a repair
# that worked is not repeated within USERNS_MIN_S, so a namespace that keeps going away cannot start a unit
# on every check. Monotonic time: the wall clock can step back after a boot.
USERNS_RETRY_S = 300
USERNS_MIN_S = 60
# `systemctl show` of an engine unit: whether it runs, and why not.
UNIT_FIELDS = ("ActiveState", "SubState", "Result", "NRestarts", "Job")
RUNNING = ("active", "reloading", "refreshing")
# A cancelled command waits this long for its child, then kills it: a `systemctl start` that a stop cancels
# must not reach systemd after that stop (delta review M2).
CANCEL_WAIT_S = 5
# After a crash of a ready engine, systemd restarts it (Restart=on-failure). Kiln waits for a test generation,
# but gives up when NRestarts grows by this many: a crash loop (delta review M3).
RESTART_LIMIT = 3


def port_answers(port: int) -> bool:
    """True if something accepts TCP connections on 127.0.0.1:port now."""
    import socket
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=1):
            return True
    except OSError:
        return False


def unit_down(unit: str, s: dict[str, str]) -> str | None:
    """Why a unit that Kiln started does not run, or None while it runs, loads or the answer is unclear.
    A unit with a queued job (the start Kiln just asked for) has not run yet, so it is not down."""
    active, sub, result = s.get("ActiveState"), s.get("SubState", ""), s.get("Result", "")
    restarts = s.get("NRestarts", "0")
    if s.get("Job"):  # a start queued after an earlier failure (a retry switch) is checked first (review L6)
        return None
    if active == "failed":
        return f"{unit} failed (result {result})"
    if sub.startswith("auto-restart"):
        return f"{unit} exited during the start and systemd will restart it (result {result}, restarts {restarts})"
    if active == "inactive":
        return f"{unit} exited (result {result})"
    return None


def _restarts(s: dict[str, str]) -> int:
    try:
        return int(s.get("NRestarts") or 0)
    except ValueError:
        return 0


def render_unit(cfg: Config, p: Profile, active: bool) -> str:
    """The unit file for a profile: Quadlet for containers, a plain service for native engines.
    Keys in profile.container / profile.native pass through unchanged: they are systemd syntax (specifiers,
    $VAR and word splitting apply), which the owner writes in kiln.toml. The label is free text."""
    if p.native:
        return render_native_unit(cfg, p, active)
    others = " ".join(o.unit for o in cfg.profiles.values() if o.name != p.name)
    lines = ["# Generated by kiln from kiln.toml; edit the profile, not this file.", "[Unit]",
             f"Description=Kiln engine {literal(p.label)}"]
    if others:
        lines.append(f"Conflicts={others}")
    lines += ["", "[Container]", f"ContainerName={p.container_name}", "Pull=never",
              f"PublishPort=127.0.0.1:{p.port}:{p.port}"]
    if "LogDriver" not in p.container:
        lines.append("LogDriver=journald")  # ingest reads engine lines by CONTAINER_NAME from the journal
    for key, value in p.container.items():
        for v in (value if isinstance(value, list) else [value]):
            lines.append(f"{key}={v}")
    lines += ["", "[Service]", "Restart=on-failure", "RestartSec=10",
              f"TimeoutStartSec={int(p.start_timeout_s)}", f"TimeoutStopSec={STOP_TIMEOUT_S}"]
    if active:
        lines += ["", "[Install]", "WantedBy=default.target"]
    return "\n".join(lines) + "\n"


def render_native_unit(cfg: Config, p: Profile, active: bool) -> str:
    others = " ".join(o.unit for o in cfg.profiles.values() if o.name != p.name)
    lines = ["# Generated by kiln from kiln.toml; edit the profile, not this file.", "[Unit]",
             f"Description=Kiln engine {literal(p.label)} (native)"]
    if others:
        lines.append(f"Conflicts={others}")
    lines += ["", "[Service]"]
    for key, value in p.native.items():
        for v in (value if isinstance(value, list) else [value]):
            lines.append(f"{key}={v}")
    lines += ["Restart=on-failure", "RestartSec=10", f"TimeoutStartSec={int(p.start_timeout_s)}",
              f"TimeoutStopSec={STOP_TIMEOUT_S}"]
    if active:
        lines += ["", "[Install]", "WantedBy=default.target"]
    return "\n".join(lines) + "\n"


def unit_file(cfg: Config, p: Profile) -> Path:
    if p.native:
        return cfg.user_unit_dir / p.unit
    return cfg.quadlet_dir / f"{p.container_name}.container"


def _kill_group(proc) -> None:
    import os
    import signal
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        with contextlib.suppress(ProcessLookupError):
            proc.kill()


async def run(*cmd: str, timeout: float = 60) -> tuple[int, str]:
    # Its own process group: a kill reaches the children too, so the pipe closes and the transport with it.
    proc = await asyncio.create_subprocess_exec(*cmd, stdout=asyncio.subprocess.PIPE,
                                                stderr=asyncio.subprocess.STDOUT, start_new_session=True)
    try:
        out, _ = await asyncio.wait_for(proc.communicate(), timeout)
    except asyncio.TimeoutError:
        _kill_group(proc)
        with contextlib.suppress(Exception):
            await asyncio.wait_for(proc.communicate(), 2)
        return 124, f"timed out after {timeout:.0f} s: {' '.join(cmd)}"
    except asyncio.CancelledError:
        # A stop cancels a switch: the child (`systemctl start --no-block`) must end first, or its start
        # could reach systemd after the stop. A child that does not end in CANCEL_WAIT_S is killed.
        try:
            await asyncio.wait_for(asyncio.shield(proc.wait()), CANCEL_WAIT_S)
        except (asyncio.TimeoutError, asyncio.CancelledError):
            _kill_group(proc)
        # Read the pipe to its end, so the transport closes now and not at garbage collection.
        with contextlib.suppress(Exception, asyncio.CancelledError):
            await asyncio.wait_for(asyncio.shield(proc.communicate()), 2)
        raise
    return proc.returncode, out.decode(errors="replace").strip()


class SwitchRefused(Exception):
    def __init__(self, message: str, confirm: bool = False):
        super().__init__(message)
        self.confirm = confirm  # the caller may repeat the request with confirm=True to override


class Manager:
    def __init__(self, cfg: Config, state: StateFile, *, on_event: Callable[[str, str | None, str], Awaitable[None]],
                 gtt_used: Callable[[], float | None], runner=run, clock=time.time, sleep=asyncio.sleep,
                 fleet=None, which=shutil.which, port_in_use: Callable[[int], bool] | None = None):
        self.cfg, self.state, self.on_event, self.gtt_used = cfg, state, on_event, gtt_used
        self.run, self.clock, self.sleep, self.which = runner, clock, sleep, which
        self.port_in_use = port_in_use if port_in_use is not None else port_answers
        if fleet is None and cfg.schedule:
            # Only a [schedule] shares the GPU with other GPU jobs; its module is not in every tree.
            from kiln.engines.fleet import Fleet
            fleet = Fleet(cfg.schedule, clock)
        self.fleet = fleet
        self.task: asyncio.Task | None = None
        self.lock = EvalLock(cfg.lock_file, clock)
        # Admission is check-then-act across awaits; one lock makes switch and stop requests take turns.
        self._admit = asyncio.Lock()
        self.probes: list[tuple[str, float, float]] = []  # (container, start, end) of health checks
        self.monotonic = time.monotonic
        self._userns_next = 0.0  # monotonic time before which no namespace repair starts
        self._repairing: str | None = None  # the unit whose crash systemd repairs now (self.task waits for it)

    # -- units ---------------------------------------------------------------
    def write_units(self, active: str | None) -> bool:
        """Write all profile units; True if any file changed."""
        changed = False
        for p in self.cfg.profiles.values():
            path = unit_file(self.cfg, p)
            path.parent.mkdir(parents=True, exist_ok=True)
            text = render_unit(self.cfg, p, p.name == active)
            if not path.exists() or path.read_text() != text:
                tmp = path.with_suffix(".tmp")
                tmp.write_text(text)
                tmp.replace(path)
                changed = True
        return changed

    async def install(self, active: str | None) -> None:
        if self.write_units(active):
            code, out = await self.run("systemctl", "--user", "daemon-reload")
            if code:
                raise RuntimeError(f"daemon-reload failed: {out[-300:]}")
        await self._boot_links(active)

    async def _boot_links(self, active: str | None) -> None:
        """Only the active engine starts at boot. The Quadlet generator links a container unit by its
        [Install] section, but a plain user unit (a native profile) boots only once it is enabled."""
        native = [p for p in self.cfg.profiles.values() if p.native]
        others = [p.unit for p in native if p.name != active]
        if others:
            code, out = await self.run("systemctl", "--user", "disable", *others)
            if code:  # the stop or switch itself went through; say that an old engine may still boot
                await self.on_event("boot_link", None, f"disable {' '.join(others)} failed: {out[-300:]}")
        if active in self.cfg.profiles and self.cfg.profiles[active].native:
            unit = self.cfg.profiles[active].unit
            code, out = await self.run("systemctl", "--user", "enable", unit)
            if code:
                raise RuntimeError(f"enable {unit} failed: {out[-300:]}")

    # -- guards ----------------------------------------------------------------
    async def blocked(self, token: str | None = None) -> str | None:
        if self.task and not self.task.done():
            if self._repairing:
                return (f"{self._repairing} restarts after a crash; wait for its test generation, or run"
                        f" `kiln stop` first")
            return "a switch is already in progress"
        if not self.lock.allows(token):
            return self.lock.describe()
        if self.cfg.busy_units:  # [engines] busy_units: user units that hold the GPU while they run
            code, out = await self.run("systemctl", "--user", "list-units", "--state=active", "--plain",
                                       "--no-legend", *self.cfg.busy_units)
            if code == 0 and out.strip():
                return f"evaluation running ({out.split()[0].removesuffix('.service')})"
        if not any(p.container for p in self.cfg.profiles.values()):
            # Native engines only: podman may be missing, and a container on such a machine is no engine.
            return None
        if self.which("podman") is None:
            return "podman is not installed, and a container profile needs it"
        code, out = await self._podman_ps()
        if code != 0:
            return f"podman ps failed: {out[-200:]}"
        mine = {p.container_name for p in self.cfg.profiles.values()}
        others = [n for n in out.split() if n not in mine]
        if others:
            # One large engine at a time: anything else holding the GPU has to stop first.
            return f"another container is running ({', '.join(sorted(others))})"
        return None

    async def _podman_ps(self) -> tuple[int, str]:
        code, out = await self.run("podman", "ps", "--format", "{{.Names}}")
        if code == 0 or not any(m in out for m in USERNS_MARKERS):
            return code, out
        now = self.monotonic()
        if now < self._userns_next:
            return code, f"no podman user namespace yet (next repair in {self._userns_next - now:.0f} s)"
        self._userns_next = now + USERNS_RETRY_S
        made, made_out = await self.run(*USERNS_MAKE)
        if made != 0:
            return code, f"no podman user namespace, and making it with systemd-run failed: {made_out[-120:]}"
        code, out = await self.run("podman", "ps", "--format", "{{.Names}}")
        if code == 0:
            self._userns_next = now + USERNS_MIN_S  # repaired: a later loss is repaired after a short wait
        return code, out

    # -- switching -------------------------------------------------------------
    async def request_switch(self, target: str, token: str | None = None, *, confirm: bool = False,
                             remember: bool = False) -> None:
        """Start a switch in the background. `confirm` lets it pause the other GPU jobs and wait
        for its running GPU jobs; `remember` makes this the profile the morning start uses."""
        p = self.cfg.profiles.get(target)
        if p is None:
            raise SwitchRefused(f"unknown profile {target!r}")
        if p.disabled:
            raise SwitchRefused(f"{p.label} is not available yet: {p.disabled}")
        async with self._admit:
            reason = await self.blocked(token)
            if reason:
                raise SwitchRefused(reason)
            leases = self.fleet.dev_leases() if self.fleet else []
            if leases and not confirm:
                from kiln.engines.fleet import describe
                raise SwitchRefused(
                    f"a development GPU job is running ({describe(leases)}); confirm to pause the fleet"
                    f" and wait up to {self.fleet.sched.drain_timeout_s / 60:.0f} min for it to finish", confirm=True)
            if remember and self.fleet:
                self.fleet.remember(target)
            self.task = asyncio.create_task(self.switch(target))

    async def stop(self, reason: str, token: str | None = None, force: bool = False) -> None:
        """Stop the active engine and leave nothing serving. During an evaluation only its holder
        (or an explicit force, the owner's emergency stop) may do this."""
        async with self._admit:
            if not force and not self.lock.allows(token):
                raise SwitchRefused(f"{self.lock.describe()}; stop with force to interrupt it")
            # A stop always works: it ends a switch in progress (for example one that waits for an engine
            # that never comes up), then stops the engine the record names.
            cancelled = await self._cancel_switch()
            await self._stop(f"{reason} (switch to {cancelled} cancelled)" if cancelled else reason)
            await self._hand_back()

    async def _cancel_switch(self) -> str | None:
        """Cancel a switch or start in progress; the profile it was going to, or None if none ran."""
        task = self.task
        if task is None or task.done():
            return None
        st = self.state.read()
        target = st.target or st.profile or "an engine"
        task.cancel()
        try:
            await task
        except asyncio.CancelledError:
            pass
        except Exception:  # the switch reports its own failures; the stop goes on
            pass
        # A repair task cancelled before its first step never runs its finally (delta review round 2, L1).
        self._repairing = None
        return target

    async def _hand_back(self) -> None:
        """After a stop: nothing starts at boot, and once the GPU memory is back the fleet may use it."""
        await self.install(None)
        if not self.fleet:
            return
        try:
            await self._wait_gtt_released("the development fleet")
        except RuntimeError as e:  # keep the hold: a fleet job on a GPU that is still full would fail
            await self.on_event("hold_kept", None, f"fleet stays paused until GPU memory returns: {e}")
            return
        self.fleet.release()

    def tidy_hold(self) -> bool:
        """Release a hold no engine needs any more: the state is stopped, no switch runs and the GPU
        memory is back. Called periodically, so a hold kept by a slow memory release or left by a
        restart never pauses the fleet for good. True if it released one. A failed state is never
        cleared here: a unit that is not active now can still start or restart (Restart=on-failure,
        activating, a failed query), so only a successful stop or a successful switch ends that hold."""
        if not self.fleet or (self.task and not self.task.done()) or not self.fleet.hold_path.exists():
            return False
        if self.state.read().state != STOPPED:
            return False
        used = self.gtt_used()
        if used is not None and used >= GTT_IDLE_BYTES:
            return False
        self.fleet.release()
        return True

    async def _stop(self, reason: str) -> None:
        cur = self.state.read()
        if cur.profile in self.cfg.profiles:
            p = self.cfg.profiles[cur.profile]
            await self._set(cur.profile, STOPPING, None, f"stopping {p.container_name}: {reason}", phase="stop")
            code, out = await self.run("systemctl", "--user", "stop", p.unit, timeout=STOP_TIMEOUT_S + 30)
            if code:
                await self._set(cur.profile, FAILED, None, f"stop {p.unit} failed: {out[-300:]}")
                raise RuntimeError(out[-300:])
        await self._set(None, STOPPED, None, reason, kind="stopped")

    async def _set(self, profile, state, target=None, detail="", kind=None, phase=None) -> ActiveState:
        # The same step told again (the fleet's leases changed) keeps its clock.
        cur = self.state.read()
        since = cur.phase_since if phase and cur.phase == phase else None
        st = self.state.set(profile, state, target, detail, now=self.clock(), phase=phase, phase_since=since)
        await self.on_event(kind or state, profile if state != STOPPING else target, detail)
        return st

    def _phase(self, phase: str) -> None:
        """A step of a switch or start inside one state (engine.phase): no event, the detail stays. Only a
        state that is changing has steps."""
        st = self.state.read()
        if st.state not in (STARTING, STOPPING) or st.phase == phase:
            return
        self.state.write(replace(st, phase=phase, phase_since=self.clock()))

    async def switch(self, target: str) -> bool:
        cur = self.state.read()
        p = self.cfg.profiles[target]
        old = self.cfg.profiles.get(cur.profile) if cur.profile else None  # the engine this switch stops
        started = False
        old_stopped = old is None  # nothing to stop, or the stop went through
        gtt_late = False  # the old engine stopped, but its GPU memory did not come back
        hold_reason = ""  # why the fleet must stay paused if this switch fails (see the handler)
        foreign = False  # another process holds the target's port; the target never started
        try:
            if self.fleet:  # before anything else, so no fleet job starts while this one is in progress
                self.fleet.hold(f"kiln: engine {target}")
            if old is not None:
                await self._set(cur.profile, STOPPING, target, f"stopping {old.container_name}", phase="stop")
                code, out = await self.run("systemctl", "--user", "stop", old.unit, timeout=STOP_TIMEOUT_S + 30)
                if code:
                    # The old engine may still serve, so the fleet must not get the GPU: it would fail.
                    hold_reason = f"{old.unit} may still run"
                    raise RuntimeError(f"stop {old.unit} failed: {out[-300:]}")
                old_stopped = True
            self._phase("drain")  # the fleet's jobs end and the GPU memory comes back
            await self._drain(target)
            try:
                await self._wait_gtt_released(target)
            except RuntimeError:
                # As _hand_back: a fleet job on a GPU that is still full would fail. The old engine still
                # holds the memory, and its unit still boots, so the record must name it, not the target.
                gtt_late = True
                hold_reason = "the GPU memory did not come back"
                raise
            own = await self.unit_status(p) if self.port_in_use(p.port) else None
            if own == {}:  # the port is taken and systemd gave no answer: it may be the target's own unit
                foreign = True  # the target never started: the record names no engine
                raise RuntimeError(f"port {p.port} is in use, and Kiln could not read the unit state of"
                                   f" {p.unit} (systemctl show failed); run `kiln switch {target}` again")
            if own and own.get("ActiveState") in (*RUNNING, "activating"):
                # The target's own unit runs (started by hand while the record said otherwise): restart it
                # with the units just written, as a switch to the running profile does.
                code, out = await self.run("systemctl", "--user", "stop", p.unit, timeout=STOP_TIMEOUT_S + 30)
                if code:
                    started = True  # it may still run: the record names it and the fleet stays paused
                    raise RuntimeError(f"stop {p.unit} failed: {out[-300:]}")
            if self.port_in_use(p.port):
                # Not our unit: every engine of Kiln is stopped now. The target would fail to bind, and the
                # test generation would reach the other process and report a ready engine that is not ours.
                foreign = True
                raise RuntimeError(f"port {p.port} is in use by another process; stop it (for example a"
                                   f" `python -m server` started by hand from the Crucible guide), then run"
                                   f" `kiln switch {target}` again")
            await self.install(target)
            await self._set(target, STARTING, None, f"starting {p.container_name}", phase="load")
            started = True
            code, out = await self.run("systemctl", "--user", "start", "--no-block", p.unit)
            if code:
                raise RuntimeError(f"start {p.unit} failed: {out[-300:]}")
            await self._wait_ready(p)
            await self._set(target, READY, None, f"{p.label} answered a test generation")
            return True
        except Exception as e:  # report every failure on the dashboard, then leave the state honest
            # The engine the record names is the old one while it may still run or still hold the GPU
            # memory: a stop that failed or raised (asyncio can raise before a status), or a stop whose
            # memory did not come back. Naming the target would lose that engine: a later stop would stop
            # the wrong unit, and its unit still boots.
            old_here = old is not None and (not old_stopped or gtt_late)
            if old_here:
                await self._set(old.name, FAILED, None, str(e)[:500])
            elif gtt_late or foreign:
                # No old engine, and install(target) never ran: the target's unit is not loaded, so a later
                # stop of it would fail and keep the hold for good. Name no engine; the stop then hands back.
                await self._set(None, FAILED, None, str(e)[:500])
            else:
                await self._set(target, FAILED, None, str(e)[:500])
            if self.fleet and not started:
                # A started engine that failed keeps the hold until someone stops it: its unit may still
                # be retrying. The same holds while the old engine was not confirmed stopped or still
                # holds the GPU memory. The decision comes from that engine state, never from a reason
                # text; the event says why. The next stop or switch settles the state and the hold.
                if old_here or gtt_late:
                    # The profile choice above is separate: with no old engine the record names the target,
                    # but a GPU whose memory did not come back still must not get a fleet job.
                    reason = hold_reason or (f"{old.unit} may still run" if old_here
                                             else "the GPU memory did not come back")
                    await self.on_event("hold_kept", None, f"fleet stays paused: {reason}: {e}")
                else:
                    self.fleet.release()  # nothing of Kiln's runs on the GPU now
            return False

    async def _drain(self, target: str) -> None:
        if not self.fleet:
            return

        from kiln.engines.fleet import describe

        async def tell(leases):
            await self._set(None, STARTING, target,
                            f"fleet paused; waiting for development GPU jobs to finish: {describe(leases)}",
                            phase="drain")
        await self.fleet.wait_drained(self.sleep, tell)

    async def _wait_gtt_released(self, target: str) -> None:
        deadline = self.clock() + GTT_WAIT_S
        while True:
            used = self.gtt_used()
            if used is None or used < GTT_IDLE_BYTES:
                return
            if self.clock() > deadline:
                raise RuntimeError(f"GPU memory still in use ({used / 2**30:.1f} GiB) {GTT_WAIT_S} s after stop")
            await self.sleep(2)

    async def unit_status(self, p: Profile) -> dict[str, str]:
        """`systemctl show` of the profile's unit; empty when systemd gives no clear answer."""
        cmd = ["systemctl", "--user", "show"]
        for f in UNIT_FIELDS:
            cmd += ["-p", f]
        code, out = await self.run(*cmd, p.unit)
        if code:
            return {}
        fields = dict(line.split("=", 1) for line in out.splitlines() if "=" in line)
        return fields if "ActiveState" in fields else {}

    async def last_log_line(self, p: Profile) -> str:
        """The last line the unit's own process wrote to the journal (not systemd's lines about it)."""
        code, out = await self.run("journalctl", "--user", "--no-pager", "--output=cat", "-n", "5",
                                   f"_SYSTEMD_USER_UNIT={p.unit}")
        lines = [ln.strip() for ln in out.splitlines() if ln.strip()] if code == 0 else []
        return lines[-1][:300] if lines else ""

    async def _down(self, p: Profile, why: str) -> str:
        last = await self.last_log_line(p)
        return f"{why}; last log line: {last}" if last else why

    async def _wait_ready(self, p: Profile, restarts_from: int | None = None) -> None:
        """Wait for a test generation. restarts_from: NRestarts when a crash of a ready engine was seen; then
        an auto-restart is no failure until NRestarts grows by RESTART_LIMIT."""
        deadline = self.clock() + p.start_timeout_s
        last = ""
        while self.clock() < deadline:
            status = await self.unit_status(p)
            why = unit_down(p.unit, status)
            if why and restarts_from is not None and status.get("SubState", "").startswith("auto-restart") \
                    and _restarts(status) - restarts_from < RESTART_LIMIT:
                why = None  # systemd repairs the crash: wait for the unit to come back
            if why:
                text = await self._down(p, why)
                # A unit that crashes restarts every 10 s (Restart=on-failure), for good: stop it, so the
                # failure stays one failure. A stop that does not go through is said, not hidden.
                code, out = await self.run("systemctl", "--user", "stop", p.unit, timeout=STOP_TIMEOUT_S + 30)
                if code:
                    text += f"; stop {p.unit} failed: {out[-200:]}"
                raise RuntimeError(text)
            ok, last = await self.probe(p)
            if ok and status and status.get("ActiveState") not in RUNNING:
                # Something answered, but the engine's own unit does not run (yet): not our engine.
                ok, last = False, f"{p.unit} is {status.get('ActiveState')}"
            if ok:
                return
            if last.startswith("HTTP ") and last != LOADING_STATUS:
                self._phase("test")
            await self.sleep(PROBE_EVERY_S)
        raise RuntimeError(f"no successful generation within {p.start_timeout_s:.0f} s ({last})")

    async def probe(self, p: Profile) -> tuple[bool, str]:
        """One real, tiny generation straight to the engine."""
        body = {"model": p.served_id, "messages": [{"role": "user", "content": "Reply with the word OK."}],
                "max_tokens": 8, "stream": False, "temperature": 0}
        start = self.clock()
        try:
            async with aiohttp.ClientSession(timeout=PROBE_TIMEOUT) as s:
                async with s.post(f"http://127.0.0.1:{p.port}/v1/chat/completions", json=body) as r:
                    text = await r.text()
            ok = r.status == 200 and (json.loads(text).get("usage") or {}).get("completion_tokens", 0) > 0
            if ok:
                self.probes = [*self.probes[-20:], (p.container_name, start - 1, self.clock() + 5)]
            return ok, f"HTTP {r.status}"
        except (aiohttp.ClientError, asyncio.TimeoutError, ValueError, OSError) as e:
            return False, type(e).__name__

    async def watch(self) -> ActiveState | None:
        """Called every few seconds by kiln-dash: a ready engine whose unit stopped, exited or crashed outside
        a switch or stop of Kiln's is no longer ready. Only a clear systemd answer changes the record. A crash
        that systemd repairs (auto-restart, or a start job) makes the engine `starting` until a test
        generation, the same test as a switch (delta review M3)."""
        if self._busy():
            return None
        st = self.state.read()
        p = self.cfg.profiles.get(st.profile or "")
        if st.state != READY or p is None:
            return None
        status = await self.unit_status(p)
        active, sub = status.get("ActiveState"), status.get("SubState", "")
        if active is None or active in RUNNING or active == "deactivating":
            return None  # running, unclear, or a stop that someone runs now: look again next round
        restarting = sub.startswith("auto-restart") or (active == "activating" and bool(status.get("Job")))
        if status.get("Job") and not restarting:
            return None  # a start that someone queued now: look again next round
        if self._busy() or self.state.read() != st:
            return None  # a switch or stop began while systemd answered
        why = f"{p.unit} is not running ({active}/{sub}, result {status.get('Result', '?')})"
        if restarting:
            # No await from the check above to here: a stop that comes later cancels this task. The record is
            # `starting` at once, so the gateway holds new requests from now on.
            detail = f"{why}; systemd restarts it; waiting for a test generation"
            st = self.state.set(p.name, STARTING, None, detail, now=self.clock(), phase="load")
            self._repairing = p.unit
            self.task = asyncio.create_task(self._repair(p, _restarts(status), detail))
            return st
        text = await self._down(p, why)
        if self._busy() or self.state.read() != st:
            return None  # a switch or stop began while the journal answered (delta review M1)
        return await self._set(p.name, FAILED, None, f"{text}; run `kiln switch {p.name}` to start it again")

    def _busy(self) -> bool:
        """A switch, a stop or a crash repair runs."""
        return self._admit.locked() or bool(self.task and not self.task.done())

    async def _repair(self, p: Profile, restarts: int, detail: str) -> None:
        """A ready engine crashed and systemd restarts it (watch() wrote `starting`): serve again after a test
        generation."""
        try:
            await self.on_event(STARTING, p.name, detail)
            await self._wait_ready(p, restarts_from=restarts)
            await self._set(p.name, READY, None, f"{p.label} answered a test generation after a restart")
        except Exception as e:  # noqa: BLE001 (a cancel by a stop or switch passes)
            await self._set(p.name, FAILED, None, f"{str(e)[:400]}; run `kiln switch {p.name}` to start it again")
        finally:
            self._repairing = None

    async def reconcile(self) -> ActiveState:
        """At startup: make the state file agree with what systemd is actually running."""
        st = self.state.read()
        if st.state in (READY, STARTING) and st.profile in self.cfg.profiles:
            p = self.cfg.profiles[st.profile]
            code, _ = await self.run("systemctl", "--user", "is-active", "--quiet", p.unit)
            if code != 0:
                return await self._reconcile_not_active(p)
            if self.fleet:  # an engine runs (for example started at boot): keep the fleet off the GPU
                self.fleet.hold(f"kiln: engine {p.name}")
            started = await self._active_since(p)
            if st.state == READY and started is not None and started > st.since:
                # It started again after the ready record (a reboot starts the enabled unit): it may still
                # load its weights, so it serves again only once it answers a test generation.
                st = await self._set(p.name, STARTING, None, f"{p.unit} restarted; waiting for a test generation",
                                     phase="test")
            if st.state == STARTING:
                self.task = asyncio.create_task(self._resume_start(p))
        elif st.state == STOPPING or (st.state == STARTING and st.profile is None):
            # Interrupted before any engine started (STARTING with no profile = waiting for fleet jobs).
            if self.fleet and st.state == STARTING:
                self.fleet.release()
            return await self._set(st.profile, STOPPED, None, "found mid-switch at startup", kind="reconcile")
        elif st.state == FAILED and st.profile in self.cfg.profiles:
            # A failed switch can leave its engine running, or about to restart (Restart=on-failure). The
            # record stays as it is and the hold stays taken: only a successful stop or switch proves that
            # nothing of Kiln's can take the GPU, so no systemd answer is trusted here.
            if self.fleet:
                self.fleet.hold(f"kiln: engine {st.profile}")
        return st

    async def _reconcile_not_active(self, p: Profile) -> ActiveState:
        """At startup the unit is not active. While systemd restarts it after a crash (RestartSec), the engine
        comes back: wait for its test generation as watch() does, instead of a record that says stopped while
        the engine loads (delta review round 2, L2)."""
        status = await self.unit_status(p)
        active, sub = status.get("ActiveState"), status.get("SubState", "")
        if sub.startswith("auto-restart") or (active == "activating" and bool(status.get("Job"))):
            if self.fleet:  # the engine takes the GPU again: keep the fleet off it
                self.fleet.hold(f"kiln: engine {p.name}")
            detail = f"{p.unit} restarts after a crash ({active}/{sub}); waiting for a test generation"
            st = await self._set(p.name, STARTING, None, detail, kind="reconcile", phase="load")
            self._repairing = p.unit
            self.task = asyncio.create_task(self._repair(p, _restarts(status), detail))
            return st
        return await self._set(p.name, STOPPED, None, f"{p.unit} is not running", kind="reconcile")

    async def _active_since(self, p: Profile) -> float | None:
        """The unix time at which the unit last became active, or None if systemd does not say."""
        code, out = await self.run("systemctl", "--user", "show", "-P", "ActiveEnterTimestamp",
                                   "--timestamp=unix", p.unit)
        text = out.strip()
        if code or not text.startswith("@"):
            return None
        try:
            return float(text[1:])
        except ValueError:
            return None

    async def _resume_start(self, p: Profile) -> None:
        try:
            await self._wait_ready(p)
            await self._set(p.name, READY, None, f"{p.label} answered a test generation")
        except Exception as e:
            await self._set(p.name, FAILED, None, str(e)[:500])

    def is_probe(self, container: str, ts: float) -> bool:
        return any(c == container and s <= ts <= e for c, s, e in self.probes)

